/** `p('01/2026')` → { label: 'Jan 2026', iso: '2026-01' } */
const p = (mmYyyy: string): Period => {
  const [mm, yyyy] = mmYyyy.split('/');
  return { label: `${MONTHS[Number(mm) - 1]} ${yyyy}`, iso: `${yyyy}-${mm}` };
};

